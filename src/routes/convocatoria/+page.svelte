  <h1 class="text-3xl font-bold mb-4 text-center">Convocatoria abierta</h1>
  <p class="text-lg text-center mb-8">Envíos a viajerevista@gmail.com</p>

  <h2 class="text-xl font-bold mb-2">Tipos de colaboraciones</h2>
  <p class="mb-4">La revista recibe colaboraciones personales vinculadas al ensayo como forma crítica y creativa, entendido como un modo de pensamiento situado, experimental y reflexivo, en diálogo con la tradición del ensayo moderno y contemporáneo, tal como fue pensada por autores como Lukács y Adorno: una forma no sistemática, fragmentaria y especulativa, que ensaya ideas sin clausurarlas y que se define por su relación analítica con, sobre todo, la experiencia de quien escribe.</p>
  <p class="mb-4">Se aceptan contribuciones en las siguientes modalidades:</p>
  <ul class="list-disc list-inside mb-4">
    <p class="mb-2 pl-4"><strong>Textos ensayísticos</strong></p>
    <ul class="list-disc list-inside ml-4">
        <li>Ensayos inéditos que desarrollen una reflexión crítica sobre la cultura, la filosofía, la política, la estética o las prácticas contemporáneas, privilegiando el ensayo como forma no sistemática, abierta y argumentativa.</li>
        <li>Ensayos breves o series de ensayos: Textos de menor extensión o conjuntos de ensayos articulados entre sí, que exploren un problema común desde distintas perspectivas, manteniendo la autonomía formal de cada pieza.</li>
    </ul>
    <p class="my-4 pl-4"><strong>Entrevistas</strong></p>
    <ul class="list-disc list-inside ml-4">
        <li>Entrevistas a autoras y autores que trabajen el ensayo como género central de su práctica intelectual o literaria, así como conversaciones que aborden procesos de escritura, pensamiento crítico, obra publicada o proyectos en desarrollo.</li>
    </ul>
    <p class="my-4 pl-4"><strong>Conversaciones públicas</strong></p>
    <ul class="list-disc list-inside ml-4">
        <li>Entrevistas o ensayos leídos en el marco de actividades públicas (charlas, seminarios, presentaciones), siempre que el material esté claramente vinculado al ensayo como forma de pensamiento.</li>
    </ul>
    <p class="my-4 pl-4"><strong>Dosieres de eventos vinculados al ensayo</strong></p>
    <ul class="list-disc list-inside ml-4">
        <li>Conjuntos de textos, intervenciones o lecturas producidas en una misma instancia (encuentros, jornadas, ciclos), articulados en torno al ensayo y a sus modos de circulación, lectura y discusión.</li>
    </ul>
  </ul>

  <h2 class="text-xl font-bold mb-2">Lineamientos generales de formato</h2>
  <p class="mb-4">Los textos deberán ajustarse a las siguientes pautas formales:</p>
  <ul class="list-disc list-inside mb-4">
    <li>Envío: archivo en formato Word (.doc o .docx). El documento deberá incluir el nombre del autor/autora/autore.</li>
    <li>Tipografía: Times New Roman, tamaño 12.</li>
    <li>Interlineado: 1,5.</li>
    <li>Alineación: justificada.</li>
    <li>Párrafos: sin espacio adicional entre ellos. La separación estándar debe realizarse mediante un renglón en blanco. Las excepciones deberán responder a decisiones estilísticas justificadas.</li>
    <li>Sangrías: no se utilizarán sangrías. Únicamente las citas separadas del cuerpo del texto deberán llevar una sangría izquierda de 1 cm.</li>
  </ul>

  <h2 class="text-xl font-bold mb-2">Material complementario</h2>
  <p class="mb-4">En el caso de ensayos inéditos y entrevistas, puede adjuntarse una imagen como propuesta visual. Esta será evaluada por el equipo editorial; de no enviarse material, la revista definirá el acompañamiento gráfico.</p>
  <p class="mb-4">Para presentaciones, deberá adjuntarse al menos un material visual pertinente (portadas de libros, fotografías del evento o del/de la autor/a entrevistado/a), en alta resolución.</p>
  <p class="mb-4">En los dosieres de eventos, además de enviar cada texto en documentos separados, deberá incorporarse:</p>
  <ul class="list-disc list-inside mb-4">
    <li>Un formulario completo con una introducción a la actividad (lugar, fecha y motivo).</li>
    <li>Un índice que indique el orden de los textos, la autoría correspondiente y las citas que se deseen destacar para el diseño gráfico.</li>
  </ul>

  <h2 class="text-xl font-bold mb-2">Extensión de los textos</h2>
  <ul class="list-disc list-inside mb-4">
    <li>Ensayos, entrevistas y presentaciones: mínimo 3 páginas y máximo 8 páginas en formato carta. En el caso de series de ensayos o entrevistas extensas, la extensión podrá distribuirse en uno o varios textos.</li>

  </ul>

  <h2 class="text-xl font-bold mb-2">Criterios editoriales de evaluación</h2>
  <p class="mb-4">Una vez recibida la propuesta, el comité editorial de Revista [viaje] evaluará su eventual publicación considerando, entre otros, los siguientes aspectos:</p>
  <ul class="list-disc list-inside mb-4">
    <li>Originalidad y enfoque reflexivo: se priorizarán textos que aporten perspectivas críticas, conceptuales o interpretativas relevantes al campo del ensayo.</li>
    <li>Calidad del pensamiento y de la escritura: se atenderá a la claridad expositiva, la coherencia argumentativa y el rigor reflexivo, así como a la solidez del estilo ensayístico.</li>
    <li>Pertinencia temática: se valorarán propuestas que dialoguen con problemáticas culturales, territoriales, literarias, políticas o filosóficas contemporáneas.</li>
    <li>Estructura y desarrollo: la organización del texto y el despliegie progresivo de las ideas serán fundamentales para garantizar una lectura articulada.</li>
    <li>Afinidad con la política editorial: No se considerarán colaboraciones que promuevan, de forma directa o indirecta, el odio, la discriminación o cualquier tipo de violencia simbólica o verbal.</li>
  </ul>

  <h2 class="text-xl font-bold mb-2">Derechos de publicación</h2>
  <p>El envío de una colaboración implica la autorización a [viaje] para publicar, reproducir y difundir el texto en sus plataformas digitales de manera no exclusiva. Los derechos de autor permanecen en todo momento en manos de sus creadores/as. Cualquier publicación posterior del texto deberá mencionar explícitamente su aparición original en Revista [viaje].</p>
